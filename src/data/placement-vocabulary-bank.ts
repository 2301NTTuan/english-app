const levels: CEFRLevel[] = ["A1", "A2", "B1", "B2", "C1", "C2"];
const sourceByLevelAndWord = new Map(vocabulary.map((item) => [`${item.cefrLevel}:${item.word.toLocaleLowerCase()}`, item]));
const stem = (context: string, index: number) => [
  `Which word best completes this sentence? “${context}”`,
  `Choose the most natural word for the gap: “${context}”`,
  `In this context, which option fits the gap? “${context}”`,
  `Complete the sentence with the most precise choice: “${context}”`,
][index % 4];

export const vocabularyPlacementQuestions: PlacementQuestion[] = groups.flatMap(([level, topic, subtopic, entries], groupIndex) => entries.map(([word, context, rationale], entryIndex) => {
  const source = sourceByLevelAndWord.get(`${level}:${word.toLocaleLowerCase()}`);
  if (!source) throw new Error(`Missing placement vocabulary source: ${level}:${word}`);
  const distractors = [1, 2, 3].map((offset) => entries[(entryIndex + offset) % entries.length][0]);
  return {
    id: `placement-vocabulary-${level.toLocaleLowerCase()}-${word.replaceAll(/[^a-z0-9]+/gi, "-").toLocaleLowerCase()}-${String(groupIndex + 1).padStart(2, "0")}`,
    itemId: source.id,
    knowledgeType: "vocabulary",
    type: "multiple-choice",
    prompt: stem(context, entryIndex + groupIndex),
    options: [word, ...distractors],
    answer: word,
    explanation: `“${word}” is the only choice that expresses the intended meaning: ${rationale}`,
    level,
    dimension: "vocabulary",
    topic,
    subtopic,
    difficulty: Math.min(0.96, (levels.indexOf(level) + 0.38 + entryIndex % 4 * 0.08) / levels.length),
    discrimination: 1.05,
    status: "validated",
    provenanceId: "placement-core-2026-08",
  };
}));
